#!/usr/bin/env python3
"""Security-review evidence helpers (spec 2026-09-28 §4-§5). Stdlib only.

Nothing here judges. It makes evidence safe to hand to a reviewer: slugs and customer ids
redacted, credentials reduced to fingerprints, and one canonical fingerprint hash.
"""
import datetime, hashlib, hmac, json, os, re

CLIENT = "<client>"
OBSERVED = "observed"
COULD_NOT_CHECK = "could-not-check"
SECRET_KEYS = ("GOOGLE_ADS_DEVELOPER_TOKEN", "GOOGLE_ADS_CLIENT_SECRET",
               "GOOGLE_ADS_REFRESH_TOKEN", "GOOGLE_ADS_CLIENT_ID")
ROLE_BY_NAME = {".env.ga": "read", ".env.gaw": "write"}


def utc_now():
    """When a bundle was collected, second precision, UTC (review #3 §5: evidence had no
    timestamp). Never part of the fingerprint, which must stay stable across runs."""
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
_MIN_SECRET_LEN = 8

# Chains Docker itself rewrites on every container create/recreate (container IPs, rule
# counts) — their declarations and rules are run-to-run volatile and must not be hashed.
# DOCKER-USER is deliberately excluded: it holds only the operator's own rules (Docker
# never writes to it), so it must stay in the hash — an operator rule added there is a
# real box-state change the fingerprint must catch.
DOCKER_MANAGED_CHAINS = {"DOCKER", "DOCKER-ISOLATION-STAGE-1", "DOCKER-ISOLATION-STAGE-2",
                          "DOCKER-CT", "DOCKER-BRIDGE", "DOCKER-FORWARD"}

# fail2ban's sshd jail bans/unbans on ~10-minute cycles on a public-SSH box: chain(s) and
# set elements named/prefixed `f2b-` are its ban list, not box configuration, and must not
# be hashed. Its liveness (is the jail running at all) is checked separately by D1.4 — the
# fingerprint only needs to ignore WHICH ips are currently banned.
FAIL2BAN_CHAIN_PREFIX = "f2b-"

_BR_ID_RE = re.compile(r"br-[0-9a-f]{12}")
# Matches only bare identifiers (`chain input {`), not quoted names (`chain "input" {`) —
# fine here because both Docker's and fail2ban's own chain names are always plain
# identifiers; nft only needs quoting for names containing characters this can't match.
_NFT_CHAIN_RE = re.compile(r"^\s*chain (\S+) \{")
_NFT_TABLE_RE = re.compile(r"^\s*table (\S+) (\S+) \{")
_NFT_F2B_JUMP_RE = re.compile(r"\b(?:jump|goto) f2b-\S+")
_NFT_COUNTER_RE = re.compile(r"counter packets \d+ bytes \d+ ?")
_IPTABLES_CHAIN_DECL_RE = re.compile(r"^:(\S+) (\S+) \[\d+:\d+\]")
_IPTABLES_RULE_CHAIN_RE = re.compile(r"^-A (\S+)\s")
_IPTABLES_F2B_TARGET_RE = re.compile(r"(?:-j|-g) f2b-\S+")


def _is_managed_chain(name):
    return name in DOCKER_MANAGED_CHAINS or name.startswith(FAIL2BAN_CHAIN_PREFIX)


def normalize_ruleset(text, kind):
    """Strip the run-to-run-volatile parts of a firewall ruleset dump so the box
    fingerprint's firewall component is stable across otherwise-identical runs.

    Volatile by kind, and why:
    - both: `br-<12 hex>` bridge interface names — Docker names each bridge randomly per
      network create, so the literal id is not a fact about the box's configuration.
    - nft: `counter packets N bytes M` — nft's own live packet/byte counters, which change
      on every packet the rule sees.
    - iptables-save: the `# Generated by … on <ts>` / `# Completed on …` header/footer
      timestamps, and each chain's `[packets:bytes]` counters — both change every run.
    - both: DOCKER_MANAGED_CHAINS are dropped entirely (declaration + every rule in them)
      because Docker rewrites them (container IPs, rule sets) on every container
      recreate. DOCKER-USER is NOT dropped — it holds only the operator's own rules, so
      it is stable and a real signal the fingerprint must keep. Rules in other chains
      that merely jump/target a Docker chain are kept: the jump itself is stable.
    - both: anything named or prefixed `f2b-` (FAIL2BAN_CHAIN_PREFIX) — fail2ban's sshd
      jail bans and unbans IPs on ~10-minute cycles, rewriting its own chain (nft) or
      chain-and-rules (iptables), an nftables banaction's whole `table inet f2b-table`
      (chain + address set), and the `jump`/`goto`/`-j`/`-g` rule elsewhere that wires it
      in on first ban. All of that is dropped; the jail's liveness is a separate
      box-state fact checked by D1.4, not by this hash.

    Known gap (not handled): Docker's per-published-port hairpin MASQUERADE rule in `nat
    POSTROUTING` (`ip saddr X ip daddr X tcp dport P masquerade`) embeds container IPs and
    is not normalised here. The box publishes no ports today, so this is dormant — the
    first published port would make the fingerprint unstable; handle it then.

    Rule order is preserved (never sorted) — it is semantically meaningful.
    """
    if kind == "nft":
        return _normalize_nft(text)
    if kind == "iptables":
        return _normalize_iptables(text)
    raise ValueError(f"unknown ruleset kind: {kind!r}")


def _clean_line(line):
    return _BR_ID_RE.sub("br-<id>", line.rstrip())


def _normalize_nft(text):
    out = []
    skip_chain = False
    skip_table_depth = 0  # >0: inside a dropped `table … f2b-… { }`, counting brace depth
    for raw in text.splitlines():
        if skip_table_depth > 0:
            skip_table_depth += raw.count("{") - raw.count("}")
            if skip_table_depth <= 0:
                skip_table_depth = 0
            continue
        tm = _NFT_TABLE_RE.match(raw)
        if tm and tm.group(2).startswith(FAIL2BAN_CHAIN_PREFIX):
            skip_table_depth = raw.count("{") - raw.count("}")
            continue
        m = _NFT_CHAIN_RE.match(raw)
        if m:
            skip_chain = _is_managed_chain(m.group(1))
        line = _clean_line(raw)
        if skip_chain:
            if line.strip() == "}":
                skip_chain = False
            continue
        if _NFT_F2B_JUMP_RE.search(raw):
            continue
        stripped = _NFT_COUNTER_RE.sub("", line)
        if stripped != line:
            stripped = re.sub(r" {2,}", " ", stripped).rstrip()
        line = stripped
        if not line.strip():
            continue
        out.append(line)
    return "\n".join(out)


def _normalize_iptables(text):
    out = []
    for raw in text.splitlines():
        if raw.startswith("#"):
            continue
        line = _clean_line(raw)
        if not line.strip():
            continue
        decl = _IPTABLES_CHAIN_DECL_RE.match(line)
        if decl:
            name = decl.group(1)
            if _is_managed_chain(name):
                continue
            line = f":{decl.group(1)} {decl.group(2)} [0:0]"
            out.append(line)
            continue
        rule = _IPTABLES_RULE_CHAIN_RE.match(line)
        if rule and _is_managed_chain(rule.group(1)):
            continue
        if _IPTABLES_F2B_TARGET_RE.search(line):
            continue
        out.append(line)
    return "\n".join(out)

# A value-shaped assignment, or Google's refresh-token prefix. `=//p'` (a sed we ran) and the
# rehearsal's placeholder are not values and must not count. Moved here from
# collect-review-evidence.py (final-review Group A) so both the collector and
# looks_like_credential_text share one definition.
CRED_TEXT_RE = re.compile(r"GOOGLE_ADS_(?:REFRESH_TOKEN|CLIENT_SECRET|DEVELOPER_TOKEN)="
                          r"(?!REHEARSAL-NOT-A-CREDENTIAL)[A-Za-z0-9_./-]{16,}|\b1//0[0-9A-Za-z_-]{20,}")
_CRED_KV_RE = re.compile(r"GOOGLE_ADS_[A-Z_]+=")


def looks_like_credential_text(text):
    """True if `text` looks like it holds (or tries to hold) a Google Ads credential
    assignment — used only to CLASSIFY a sweep hit the KEY=VALUE parser could not
    fingerprint (kind: unparsed), never to extract or print a value."""
    return bool(_CRED_KV_RE.search(text) or CRED_TEXT_RE.search(text))


def sha12(value):
    """sha1 of the bare value, first 12 hex — audit-credential-access.py:95's convention."""
    return hashlib.sha1(str(value).encode()).hexdigest()[:12]


def hmac12(key, value):
    """Keyed customer-id fingerprint (Option B §8): a 10-digit id cannot be brute-forced
    from it without the review key, which lives only on the operator's laptop."""
    return hmac.new(key, str(value).encode(), hashlib.sha256).hexdigest()[:12]


def load_fp_key(text):
    t = (text or "").strip()
    if not re.fullmatch(r"[0-9a-f]{64}", t):
        raise ValueError("the review fingerprint key must be 64 lowercase hex characters")
    return bytes.fromhex(t)


def key_id(key):
    return hashlib.sha256(key).hexdigest()[:8]


def canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


class Redactor:
    def __init__(self, slugs, customer_ids, fp_key=None):
        self._fp = (lambda d: hmac12(fp_key, d)) if fp_key else sha12
        self._slugs = sorted({s for s in slugs if s}, key=len, reverse=True)
        # Normalise to digits FIRST: a customer_id already stored dashed in
        # clients.json (e.g. "123-456-7890") must still redact both the dashed and
        # the plain-digit forms it can appear as elsewhere in evidence, not just its
        # own literal spelling (final-review Group E4).
        digits = set()
        for c in customer_ids:
            if not c:
                continue
            d = "".join(ch for ch in str(c) if ch.isdigit())
            if d:
                digits.add(d)
        self._cids = []
        for d in sorted(digits, key=len, reverse=True):
            self._cids.append((d, d))
            if len(d) == 10:
                self._cids.append((f"{d[:3]}-{d[3:6]}-{d[6:]}", d))

    @classmethod
    def from_clients_json(cls, path, fp_key=None):
        """Raises ValueError if the registry cannot be read — the caller must then refuse to
        print anything, because it no longer knows what to hide."""
        try:
            with open(path, encoding="utf-8") as f:
                clients = json.load(f).get("clients", {})
        except (OSError, ValueError, AttributeError) as e:
            raise ValueError(f"cannot load the redaction list: {type(e).__name__}")
        if not isinstance(clients, dict):
            raise ValueError("cannot load the redaction list: 'clients' is not an object")
        return cls(list(clients), [(v or {}).get("customer_id", "") for v in clients.values()
                                   if isinstance(v, dict)], fp_key=fp_key)

    def text(self, s):
        for raw, digits in self._cids:
            s = s.replace(raw, "cid:" + self._fp(digits))
        for slug in self._slugs:
            s = re.sub(rf"(?<![A-Za-z0-9]){re.escape(slug)}(?![A-Za-z0-9])", CLIENT, s)
        return s

    def obj(self, o):
        if isinstance(o, str):
            return self.text(o)
        if isinstance(o, dict):
            return {self.text(k) if isinstance(k, str) else k: self.obj(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return [self.obj(v) for v in o]
        return o


def parse_credential_file(path):
    """(info, secrets). Values never leave this function except as sha12 fingerprints —
    `secrets` exists only so the caller can prove none reached its output."""
    values = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            if line.startswith("export "):
                line = line[len("export "):].lstrip()
            k, _, v = line.partition("=")
            k, v = k.strip(), v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
                v = v[1:-1]
            values[k] = v
    role = values.get("GOOGLE_ADS_CREDENTIAL_ROLE") or ROLE_BY_NAME.get(os.path.basename(path), "unknown")
    rt, ci = values.get("GOOGLE_ADS_REFRESH_TOKEN", ""), values.get("GOOGLE_ADS_CLIENT_ID", "")
    info = {"path": path, "role": role,
            "refresh_token_sha12": sha12(rt) if rt else None,
            "client_id_sha12": sha12(ci) if ci else None}
    return info, [values[k] for k in SECRET_KEYS if values.get(k)]


def credential_set(infos):
    rows = [{"role": i["role"], "refresh_token_sha12": i["refresh_token_sha12"],
             "client_id_sha12": i["client_id_sha12"]} for i in infos]
    return sorted(rows, key=lambda r: canon(r))


def fingerprint(components):
    digests = {k: hashlib.sha256(canon(v)).hexdigest() for k, v in sorted(components.items())}
    complete = not any(isinstance(v, dict) and COULD_NOT_CHECK in v for v in components.values())
    return {"fingerprint": hashlib.sha256(canon(digests)).hexdigest(),
            "components": digests, "complete": complete}


def assert_no_secret(text, secrets):
    """The last line of defence: refuse to print if any credential value is present. Never
    says which one."""
    for s in secrets:
        if len(s) >= _MIN_SECRET_LEN and s in text:
            raise RuntimeError("output would contain a credential value — refusing to print")
